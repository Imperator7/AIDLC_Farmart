import { readFile } from "node:fs/promises";
import path from "node:path";

export const dynamic = "force-static";

/** GET /database-er-diagram/mermaid.min.js: Mermaid from node_modules, served from our origin because the CSP blocks CDNs. */
export async function GET() {
  const js = await readFile(path.join(process.cwd(), "node_modules", "mermaid", "dist", "mermaid.min.js"), "utf8");
  return new Response(js, {
    headers: { "Content-Type": "text/javascript; charset=utf-8", "Cache-Control": "public, max-age=86400" },
  });
}
