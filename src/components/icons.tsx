import type { SVGProps } from "react";

/**
 * Small line icons (DESIGN.md › Components › Icons): 24px grid, currentColor, 2px stroke, round caps.
 * They replace Unicode glyphs (‹ › × ⏱ ✓ ★), which render differently per font and can't be sized or aligned reliably.
 */
type IconProps = SVGProps<SVGSVGElement> & { size?: number };

function Svg({ size = 16, children, ...rest }: IconProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      // Decorative by default; an icon given an aria-label is the content itself (e.g. a pass/fail mark), so keep it visible to assistive tech.
      aria-hidden={rest["aria-label"] ? undefined : true}
      focusable="false"
      {...rest}
    >
      {children}
    </svg>
  );
}

